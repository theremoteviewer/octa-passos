; ---------------------------------------------------------------------------
; The percussion engines: mechanisms, not parameter sets.
;
; Three renderers in the noise family, each a different way of making a sound.
; They share bdnoise.asm's LCG, its state-variable filter idiom, its knob
; decode and its clamp, and they share the 909's voice block the same way --
; one engine runs on a track, never two.
;
; ⚠️ WHY THESE EXIST. The family had five rows and ONE renderer, and Jesse's
; verdict after flashing it was "the different decay times are cool, but I'm
; looking for each sound to be different" (5 Oct 2026). Every distinctness
; gate I had passed, because they all measured PARAMETERS. A parameter is not a
; mechanism: band-passed noise with a long decay is still band-passed noise.
; So a machine now names its renderer (dspnoise.BASES' engine field) and the
; separation gate counts a different renderer as absolute.
;
; The model set is the one Mutable Instruments' Plaits offers -- analog kick,
; analog snare and analog hi-hat, each a classic circuit rather than a sample
; -- which is what Jesse asked for. Plaits is MIT-licensed, (c) Emilie Gillet,
; and credited as the reference for WHICH models are worth having.
;
; ⚠️ NOT A PORT OF PLAITS, AND NOT MATCHED TO IT. The Plaits sources could not
; be fetched in the session that wrote this (GitHub is blocked here), and there
; is no Plaits hardware or emulator in this container to capture reference audio
; from, so there is nothing to measure against. These are reimplementations
; from published circuit behaviour -- the TR-808's six-oscillator hi-hat, a
; two-mode snare shell with a noise bed, a clap's burst train -- and the gates
; are structural: it sounds, it fills the block, it stops, it survives
; retriggering, and no two machines in the browser share a mechanism OR a
; reachable parameter. Nothing here claims to be within x% of a real Plaits.
; Generated by dspperc.py.
; ---------------------------------------------------------------------------

; ===========================================================================
; zh: the metallic hi-hat -- six square oscillators -> high-pass -> VCA
; ===========================================================================
; The TR-808's hi-hat and cymbal share six square oscillators at fixed
; inharmonic frequencies (205.3, 304.4, 369.6, 522.7, 540.0 and 800.0 Hz,
; documented in the service notes and reproduced by every clone since). Summed,
; they give a dense cluster of mutually inharmonic partials; the metallic
; character is that cluster heard through a high corner, not the oscillators
; themselves. So this is NOTHING like a band-pass on noise, which is the whole
; reason it is here: noise has no partials to be inharmonic.
;
; PITCH transposes the whole set (the top oscillator takes the band curve's
; frequency, the other five follow as fixed ratios of it), DECAY is the VCA's
; fall and WIDTH is the high-pass corner.
zh01:
; the six increments, once per block: inc[k] = top * ratio[k].
; The top oscillator's increment comes from the band curve: N_F holds
; sin(pi*fc/SR) and a phase increment is fc/SR, so inc = N_F/pi -- within 0.1%
; across this engine's range, because sin(x)/x is 0.9995 at 800 Hz and the
; error only matters where no oscillator runs.
        move x:(r5+@F@),x0
        move #>@RECIPPI@,y0
        mpy y0,x0,a
        move a,y1
        move y1,x:(r5+@I5@)     ; ratio 1.0 is the top oscillator itself
; SPRD (knob 3): how far apart the six oscillators sit.
;   ratio_eff[k] = 1 - w*(1 - ratio[k]),   w = knob/64
; so knob 64 is w = 1 and the set is EXACTLY the 808's -- the default Part
; renders the machine this engine was written as. Below 64 the six close toward
; unison, which is a pitched square rather than a cluster; above it they
; spread wider.
; ⚠️ CLAMPED AT w = 1.25, AND THE CAP IS ARITHMETIC, NOT TASTE. The lowest
; ratio is 0.2566, so 1 - w*(1 - 0.2566) goes negative past w = 1.345: the
; oscillator would run BACKWARDS at a frequency the knob no longer controls,
; which is a different machine and not a wider one.
; w/2 is knob << 16, one instruction, exact: a1 holds the integer 0..127 and
; shifting it sixteen places is knob/128.
        move x:(r6+$3),a
        asl #$10,a,a
        move #>@SPRDMAX@,x0
        tfr a,b
        move #>@SPRDMAX@,a
        sub b,a                 ; flags: cap - w/2
        tmi x0,b                ; past the cap -> the cap
        tfr b,a
        move a1,x0
        move x0,x:(r5+@HPM@)    ; w/2, parked: every oscillator needs it
        move #>@OMR0@,x0
        bsr zh08
        move y1,x:(r5+@I0@)
        move #>@OMR1@,x0
        bsr zh08
        move y1,x:(r5+@I1@)
        move #>@OMR2@,x0
        bsr zh08
        move y1,x:(r5+@I2@)
        move #>@OMR3@,x0
        bsr zh08
        move y1,x:(r5+@I3@)
        move #>@OMR4@,x0
        bsr zh08
        move y1,x:(r5+@I4@)
; RES (knob 4): the band-pass Q. Read ABSOLUTELY through the family's width
; curve rather than as a trim, because it is a voicing knob and not part of
; what makes this row a machine; 64 lands on Q 3.4, where the fixed constant
; it replaces was 2.
        move x:(r6+$4),a
        asr #$1,a,a
        move a1,n1
        move #>@N_DAMP@,r1
        move x:(r1+n1),x0
        move x0,x:(r5+@DAMP@)
; HPK already holds the band-pass coefficient: the decode puts N_F[width]
; there, which is where the metal is for this engine.
; the trig convention is the 808's: knob $c is the frame offset, or negative
        move x:(r6+$c),a
        tst a
        blt zh03
        move a,x:(r5+@SEG@)
        bsr zh04
        bsr zh06
        move n7,a
        move x:(r5+@SEG@),x0
        sub x0,a
        bsr zh04
        rts
zh03:
        move n7,a
        bsr zh04
        rts
; --- zh04: render `a` samples ----------------------------------------------
zh04:
        tst a
        beq zh05
        do a,zh07
; ⚠️ THE WEIGHTS ARE LOADED ONCE, OUTSIDE NOTHING. x0 is +1/6 and x1 is -1/6
; for every oscillator, so they are set up here rather than six times; y0 takes
; each increment and y1 is the wrap scratch. b accumulates the sum.
        move #>@WPLUS@,x0
        move #>@WMINUS@,x1
        clr b
; ⚠️ `move a1,y1` IS THE WRAP, AND IT IS NOT OPTIONAL. A phase that keeps
; accumulating in a 56-bit accumulator does not wrap at 24 bits, and
; `move a,x:(...)` SATURATES -- the oscillator would clamp at full scale and
; stop oscillating within a few hundred samples. Taking a1 through a register
; discards the extension byte, which IS modulo 1.0, and a register store does
; not limit.
        move x:(r5+@P0@),a
        move x:(r5+@I0@),y0
        add y0,a
        move a1,y1
        move y1,x:(r5+@P0@)
        move y1,a
        tst a
        move x0,a
        tmi x1,a
        add a,b
        move x:(r5+@P1@),a
        move x:(r5+@I1@),y0
        add y0,a
        move a1,y1
        move y1,x:(r5+@P1@)
        move y1,a
        tst a
        move x0,a
        tmi x1,a
        add a,b
        move x:(r5+@P2@),a
        move x:(r5+@I2@),y0
        add y0,a
        move a1,y1
        move y1,x:(r5+@P2@)
        move y1,a
        tst a
        move x0,a
        tmi x1,a
        add a,b
        move x:(r5+@P3@),a
        move x:(r5+@I3@),y0
        add y0,a
        move a1,y1
        move y1,x:(r5+@P3@)
        move y1,a
        tst a
        move x0,a
        tmi x1,a
        add a,b
        move x:(r5+@P4@),a
        move x:(r5+@I4@),y0
        add y0,a
        move a1,y1
        move y1,x:(r5+@P4@)
        move y1,a
        tst a
        move x0,a
        tmi x1,a
        add a,b
        move x:(r5+@P5@),a
        move x:(r5+@I5@),y0
        add y0,a
        move a1,y1
        move y1,x:(r5+@P5@)
        move y1,a
        tst a
        move x0,a
        tmi x1,a
        add a,b
; ⚠️ A RESONANT BAND-PASS, NOT A HIGH-PASS. Two things went wrong with a
; high-pass. A hard square is not band-limited, so its energy runs all the way
; to Nyquist: high-passing a 205-800 Hz square sum does not reveal metal, it
; reveals ALIASING -- measured peak 16,365 Hz and the level down 37 dB, which
; is digital trash, not a hi-hat. And one pole left the fundamentals only
; 6 dB/octave down, so the spectral peak landed on one of them at 947 Hz, a
; bass note. The 808 puts its six oscillators through a band-pass around the
; bright register and that is what makes the sound. The family's own SVF does
; it in ten instructions, fewer than the two poles it replaces.
;
; f is N_F[width] -- the width knob is "where the metal is" for this engine --
; and the damp is a fixed moderate Q, because a hat does not want a knob that
; can ring it into a tone.
        move b,x0               ; the oscillator sum, +-0.5
        move x:(r5+@LOW@),y1
        move x0,b
        sub y1,b                ; b = sum - low
        move x:(r5+@BAND@),x0
        move x:(r5+@DAMP@),y0   ; RES: N_DAMP[knob 4], not a fixed Q any more
        mpy y0,x0,a
        asl a                   ; damp is stored halved, as N_DAMP is
        sub a,b                 ; b = high
        move x:(r5+@HPK@),y0    ; f = N_F[width]
        move b,x0
        mpy y0,x0,a
        asl a
        move x:(r5+@BAND@),b
        add a,b
        move b,x:(r5+@BAND@)
        move b,x0
        mpy y0,x0,a
        asl a
        move x:(r5+@LOW@),b
        add a,b
        move b,x:(r5+@LOW@)
        move x:(r5+@BAND@),a
        move a,x1               ; x1 = the band-passed metal
; envelope: e -= de*e
        move x:(r5+@ENV@),b
        move b,x0
        move x:(r5+@DE@),y0
        mpy y0,x0,a
        sub a,b
        move b,x:(r5+@ENV@)
; out = hp * env * gain, twice: the source block is interleaved stereo
        move b,y0
        move x1,x0
        mpy y0,x0,a
        move a,x0
        move x:(r5+@GAIN@),y0
        mpy y0,x0,a
        asl a                   ; DRIVE: GAIN carries 1/8 .. 1 and these three
        asl a                   ; shifts give 1x .. 8x, with the store's own
        asl a                   ; limiter as the clipper (knob 5)
        move a,x:(r0)+
        move a,x:(r0)+
zh07:
zh05:
        rts
; --- zh06: the trig -------------------------------------------------------
; ⚠️ ZERO WHAT WE READ, INCLUDING THE PHASES. These words are the 909's: a
; track that was a 909 and is now a hat hands this engine six phases and a
; filter state full of someone else's numbers. The phases are spread rather
; than all set to zero, because six oscillators starting in phase give one
; click and no cluster -- the spread is what makes the first millisecond
; metallic instead of a thud.
zh06:
        clr a
        move a,x:(r5+@BAND@)
        move a,x:(r5+@LOW@)
        move #>$000000,a
        move a,x:(r5+@P0@)
        move #>$155555,a
        move a,x:(r5+@P1@)
        move #>$2aaaaa,a
        move a,x:(r5+@P2@)
        move #>$400000,a
        move a,x:(r5+@P3@)
        move #>$555555,a
        move a,x:(r5+@P4@)
        move #>$6aaaaa,a
        move a,x:(r5+@P5@)
        move #>$7fffff,a
        move a,x:(r5+@ENV@)
        rts
; --- zh08: one oscillator's increment -------------------------------------
; In:  x0 = 1 - ratio[k] (a constant), HPM = w/2, I5 = the top increment.
; Out: y1 = top * (1 - w*(1 - ratio[k])), ready to store.
; A subroutine rather than five copies because it runs once per block and
; eleven words times five is a hundred P words of the ground for nothing.
zh08:
        move x:(r5+@HPM@),y0
        mpy y0,x0,a             ; (w/2) * (1 - ratio)
        asl a                   ; w * (1 - ratio)
        move #>$7fffff,b
        sub a,b                 ; b = ratio_eff, positive for every capped w
        move b,y0
        move x:(r5+@I5@),x0     ; the top oscillator's own increment
        mpy y0,x0,a
        move a,y1
        rts

; ===========================================================================
; zs: the snare -- two rung resonator bodies + band-passed noise
; ===========================================================================
; A snare is a shell with two strong modes and a bed of wires. Each body is a
; state-variable filter at very high Q, struck with an impulse at the trig and
; left to ring; its decay comes from an amplitude envelope rather than from the
; Q, so PITCH and DECAY stay independent -- which they are not in a resonator
; whose damping sets both. The wires are the family's LCG through a third,
; wide filter with its own envelope. PITCH is the first mode (the second is a
; fixed 1.83 above it, the ratio a real shell has), DECAY the bodies' fall and
; WIDTH the mix: more wires as it rises.
zs01:
; RATIO (knob 3): where body 2 sits above body 1. A real 14-inch shell's two
; strong modes are about 1.83 apart and knob 64 is exactly that, so the
; default Part is the shell this engine was fitted to; the knob runs 1.03 to
; 3.62, from a doubled fundamental to a hand drum.
; ⚠️ A QUARTER OF THE RATIO, AND TWO SHIFTS. The obvious half-and-one-`asl`
; (what the fixed 1.83 used) tops out at ratio 2: `move a,y0` LIMITS at 1.0,
; so a ratio/2 above unity silently stops moving and two thirds of the knob
; would do nothing -- a parameter that works only at the bottom of its travel.
        move x:(r6+$3),a
        asl #$10,a,a            ; knob/128
        move a1,x0
        move #>@SNRSPAN@,y0
        mpy y0,x0,a
        move #>@SNRBASE@,x0
        move x0,b
        add b,a                 ; a = ratio/4
        move a,y0
        move x:(r5+@F@),x0
        mpy y0,x0,a
        asl a
        asl a                   ; a = ratio * F, both halved alike
        move a,x0
        move x0,x:(r5+@F2@)
; NDEC (knob 4): how long the wires ring on past the shell, read absolutely
; through the family's own decay curve. 64 is 99 ms, where the fixed constant
; it replaces was 180.
        move x:(r6+$4),a
        asr #$1,a,a
        move a1,n1
        move #>@N_DE@,r1
        move x:(r1+n1),x0
        move x0,x:(r5+@NDE2@)
; the trig convention is the 808's: knob $c is the frame offset, or negative
        move x:(r6+$c),a
        tst a
        blt zs03
        move a,x:(r5+@SEG@)
        bsr zs04
        bsr zs06
        move n7,a
        move x:(r5+@SEG@),x0
        sub x0,a
        bsr zs04
        rts
zs03:
        move n7,a
        bsr zs04
        rts
; --- zs04: render `a` samples ---------------------------------------------
zs04:
        tst a
        beq zs05
        do a,zs07
; ---- body 1: a high-Q SVF left ringing from the trig's impulse ----------
; ⚠️ THE DECAY IS THE ENVELOPE'S, NOT THE Q'S. A resonator whose damping sets
; its decay cannot have pitch and decay as separate controls -- raise the Q to
; lengthen the ring and the tone narrows with it. So the Q is fixed and very
; high (the body rings essentially forever) and an amplitude envelope does the
; decaying, which is what makes DECAY independent of PITCH on this engine.
        move x:(r5+@LOW@),y1
        clr b
        sub y1,b                ; no input: a struck body rings on its own
        move x:(r5+@BAND@),x0
        move #>@SNRDAMP@,y0
        mpy y0,x0,a
        asl a
        sub a,b                 ; b = high
        move x:(r5+@F@),y0
        move b,x0
        mpy y0,x0,a
        asl a
        move x:(r5+@BAND@),b
        add a,b
        move b,x:(r5+@BAND@)
        move b,x0
        mpy y0,x0,a
        asl a
        move x:(r5+@LOW@),b
        add a,b
        move b,x:(r5+@LOW@)
; ---- body 2, the same, a fixed ratio up --------------------------------
        move x:(r5+@B2L@),y1
        clr b
        sub y1,b
        move x:(r5+@B2B@),x0
        move #>@SNRDAMP@,y0
        mpy y0,x0,a
        asl a
        sub a,b
        move x:(r5+@F2@),y0
        move b,x0
        mpy y0,x0,a
        asl a
        move x:(r5+@B2B@),b
        add a,b
        move b,x:(r5+@B2B@)
        move b,x0
        mpy y0,x0,a
        asl a
        move x:(r5+@B2L@),b
        add a,b
        move b,x:(r5+@B2L@)
; ---- the two bodies, summed and enveloped ------------------------------
        move x:(r5+@BAND@),a
        move x:(r5+@B2B@),x0
        move x0,b
        add b,a
        asr #$1,a,a             ; the mean, so two bodies cannot overflow one
        move a1,y1              ; y1 = the shell
; ---- the wires: the family's LCG through a wide filter -----------------
        move x:(r5+@LCG@),x0
        move #>@LCGK@,y0
        mpy y0,x0,b             #0,x1
        add x,b                 #>@LCGC@,y0
        move #0,y1
        add y,b
        move b0,x0
        move x0,x:(r5+@LCG@)
        move x:(r5+@NL@),y1
        move x0,b
        sub y1,b
        move x:(r5+@NB@),x0
        move #>@SNRNDMP@,y0
        mpy y0,x0,a
        asl a
        sub a,b
        move #>@SNRNF@,y0
        move b,x0
        mpy y0,x0,a
        asl a
        move x:(r5+@NB@),b
        add a,b
        move b,x:(r5+@NB@)
        move b,x0
        mpy y0,x0,a
        asl a
        move x:(r5+@NL@),b
        add a,b
        move b,x:(r5+@NL@)
; ---- the two envelopes -------------------------------------------------
        move x:(r5+@ENV@),b
        move b,x0
        move x:(r5+@DE@),y0
        mpy y0,x0,a
        sub a,b
        move b,x:(r5+@ENV@)
        move x:(r5+@ENV2@),b
        move b,x0
        move x:(r5+@NDE2@),y0   ; NDEC (knob 4), not a fixed 180 ms
        mpy y0,x0,a
        sub a,b
        move b,x:(r5+@ENV2@)
; ---- out = shell*env*(1-mix) + wires*env2*mix --------------------------
        move x:(r5+@BAND@),a
        move x:(r5+@B2B@),x0
        move x0,b
        add b,a
        asr #$1,a,a
        move a1,x0
        move x:(r5+@ENV@),y0
        mpy y0,x0,a
        move a,x0
        move x:(r5+@BGN@),y0
        mpy y0,x0,a
        move a,y1               ; y1 = the shell's contribution
        move x:(r5+@NB@),x0
        move x:(r5+@ENV2@),y0
        mpy y0,x0,a
        move a,x0
        move x:(r5+@MIX@),y0
        mpy y0,x0,a
        move y1,b
        add b,a                 ; a = shell + wires
        move a,x0
        move x:(r5+@GAIN@),y0
        mpy y0,x0,a
        asl a                   ; DRIVE (knob 5): 1x .. 8x into the store's
        asl a                   ; own limiter, which is the clipper
        asl a
        move a,x:(r0)+
        move a,x:(r0)+
zs07:
zs05:
        rts
; --- zs06: the trig -------------------------------------------------------
; ⚠️ STRIKE THE BODIES, ZERO EVERYTHING ELSE. An impulse into BAND and B2B is
; what makes a resonator ring; the other words are the 909's leftovers and
; would ring on their own.
zs06:
        clr a
        move a,x:(r5+@LOW@)
        move a,x:(r5+@B2L@)
        move a,x:(r5+@NB@)
        move a,x:(r5+@NL@)
        move #>@SNRHIT@,a
        move a,x:(r5+@BAND@)
        move a,x:(r5+@B2B@)
        move #>$7fffff,a
        move a,x:(r5+@ENV@)
        move a,x:(r5+@ENV2@)
        rts

; ===========================================================================
; zp: the clap -- a burst train into a longer tail
; ===========================================================================
; Three short bursts of band-passed noise a few milliseconds apart, then a
; fourth that decays slowly: the measured 26 ms attack that one envelope could
; not reproduce, which is why claps were left out of the Machinedrum set.
; ⚠️ THE BURST BOUNDARY IS TESTED ONCE PER BLOCK, NOT PER SAMPLE. A block is
; 16 samples -- 0.36 ms -- and the bursts are 11.6 ms apart, so block
; granularity is inaudible and it keeps every branch OUT of the sample loop.
; The alternative was a per-sample counter test with two conditions ANDed,
; which is three branches inside a `do` loop for a timing resolution nothing
; can hear.
;
; PITCH is the bursts' band, DECAY the wash's length, WIDTH how much wash.
zp01:
; SPRD (knob 3): the gap between bursts, in samples, as knob*4 -- 5.8 ms at
; 64, 1.5 to 11.5 ms across the knob. Floored at 64 samples, because a gap of
; zero fires every burst into the same sample and the engine becomes one hit.
        move x:(r6+$3),a
        asl #$2,a,a             ; knob * 4 samples
        move #>$40,x0
        tfr a,b
        move #>$40,a
        sub b,a                 ; flags: 64 - gap
        tpl x0,b                ; gap <= 64 -> 64
        tfr b,a
        move a1,x0
        move x0,x:(r5+@CGAP@)
; REPS (knob 4): how many MORE bursts after the trig's own, knob >> 4. Four at
; 64, so the default is five bursts 5.8 ms apart -- a 23 ms attack, which is
; what the real machines measure, and what the fixed three-at-11.6 ms this
; replaces was reaching for.
        move x:(r6+$4),a
        asr #$4,a,a
        move a1,x0
        move x0,x:(r5+@CREP@)
; the trig convention is the 808's: knob $c is the frame offset, or negative
        move x:(r6+$c),a
        tst a
        blt zp03
        move a,x:(r5+@SEG@)
        bsr zp04
        bsr zp06
        move n7,a
        move x:(r5+@SEG@),x0
        sub x0,a
        bsr zp04
        rts
zp03:
        move n7,a
        bsr zp04
        rts
; --- zp04: render `a` samples ---------------------------------------------
zp04:
        tst a
        beq zp05
; ---- has the next burst come due? ---------------------------------------
        move a,y1               ; keep the sample count
        move x:(r5+@CNT@),b
        move x:(r5+@NXT@),x0
        move x0,a
        sub b,a                 ; a = next - cnt
        bgt zp08                ; not yet
; ⚠️ A TALLY OF BURSTS FIRED, NOT A BOUNDARY IN SAMPLES. The boundary used to
; be gap x count, and with both of those now knobs that is an integer multiply
; the decode has no cheap, honest form for -- `mpy` reading a0 is the trap
; AGENTS.md records (the product comes back at twice the scale). Counting the
; bursts instead needs one more state word and no multiply at all.
        move x:(r5+@CBN@),a
        move x:(r5+@CREP@),x0
        move x0,b
        sub b,a                 ; every burst fired?
        bge zp08
        move #>$7fffff,a        ; restart the fast envelope: another clap
        move a,x:(r5+@ENV@)
        move x:(r5+@CBN@),a
        add #>$1,a
        move a,x:(r5+@CBN@)
        move x:(r5+@NXT@),a
        move x:(r5+@CGAP@),x0
        move x0,b
        add b,a
        move a,x:(r5+@NXT@)
zp08:
