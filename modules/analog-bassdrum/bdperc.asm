; ===========================================================================
; zf: two-operator FM -- bells, zaps, woodblocks, synthetic toms
; ===========================================================================
; A carrier phase-modulated by a second oscillator, with the modulation index
; falling as the note decays. That is the whole of 2-op FM percussion, and it
; is a mechanism none of the other engines have: the oscillators here are
; PITCHED and the inharmonicity comes from the ratio between them, where the
; hat's comes from six fixed detunings and the snare's from two resonances.
; Bright and metallic at a high ratio, a woodblock at a low one, a synthetic
; tom when the index falls fast.
;
; PITCH is the carrier, DECAY the amplitude fall, WIDTH the modulator's ratio
; AND the index together -- one knob from "woodblock" to "gong", which is the
; useful axis and keeps the engine to five state words.
;
; ⚠️ NO SINE TABLE, AND NONE TO SPARE. Free private X ends exactly on the
; measured free top, so a 256-word sine was never available. A parabola does
; it in three instructions: for a phase p in -1..1, 4*p*(1-|p|) is a sine to
; within about 2% -- audibly a sine, and its harmonic error is a fifth of what
; the squares in the hat engine put out on purpose.
zf01:
; the two increments: carrier from the band curve (inc = N_F/pi, as the hat
; derives it), modulator = carrier * ratio, the ratio taken from WIDTH's own
; lookup so one knob moves brightness and pitch-relationship together.
        move x:(r5+@F@),x0
        move #>@RECIPPI@,y0
        mpy y0,x0,a
        move a,y1
        move y1,x:(r5+@FIC@)
        move x:(r5+@HPK@),x0    ; N_F[width]: the modulator's own frequency
        move #>@RECIPPI@,y0
        mpy y0,x0,a
        move a,y1
        move y1,x:(r5+@FIM@)
; INDEX (knob 3): how much modulation, on its own knob at last. This used to
; be MIX -- knob 2's own 0..1 ramp -- so RATIO moved the modulator's frequency
; AND its depth together and there was no way to ask for a deep modulation at
; a low ratio, or a clean sine at a high one. Knob 64 reads the same table
; entry the old shared knob did at its own 64, so a default Part is unchanged.
        move x:(r6+$3),a
        move a1,n1
        move #>@N_VEL@,r1
        move x:(r1+n1),x0
        move x0,x:(r5+@FIA@)
; IDEC (knob 4): how fast the index falls, read absolutely through the family's
; decay curve. It used to fall with the AMPLITUDE envelope, which ties "how
; long the note lasts" to "how long it stays bright" -- two different things
; on every FM drum ever programmed. 64 is 99 ms.
        move x:(r6+$4),a
        asr #$1,a,a
        move a1,n1
        move #>@N_DE@,r1
        move x:(r1+n1),x0
        move x0,x:(r5+@FIR@)
; the trig convention is the 808's: knob $c is the frame offset, or negative
        move x:(r6+$c),a
        tst a
        blt zf03
        move a,x:(r5+@SEG@)
        bsr zf04
        bsr zf06
        move n7,a
        move x:(r5+@SEG@),x0
        sub x0,a
        bsr zf04
        rts
zf03:
        move n7,a
        bsr zf04
        rts
; --- zf04: render `a` samples ---------------------------------------------
zf04:
        tst a
        beq zf05
        do a,zf07
; ---- the modulator: phase, then the parabola ---------------------------
        move x:(r5+@FPM@),a
        move x:(r5+@FIM@),y0
        add y0,a
        move a1,y1
        move y1,x:(r5+@FPM@)
; para(p) = 4*p*(1-|p|), built as 2*p*(1-|p|) and doubled: 2*p does not fit
; Q23 for p near 1, and the product does.
        move y1,a
        abs a
        move #>$7fffff,b
        move a,x0
        move x0,y0
        move b,a
        sub y0,a                ; a = 1 - |p|
        move a,x0
        move y1,y0
        mpy y0,x0,a             ; a = p*(1-|p|)
        asl a
        asl a                   ; a = 4*p*(1-|p|), the modulator's sine
; ---- the carrier: phase + index*modulator ------------------------------
        move a,x0
        move x:(r5+@FIX@),y0
        mpy y0,x0,a             ; a = index * modulator
        move a,y1               ; y1 = the phase offset
        move x:(r5+@FPC@),a
        move x:(r5+@FIC@),y0
        add y0,a
        move a1,x1
        move x1,x:(r5+@FPC@)    ; the carrier's own phase, wrapped and kept
        move x1,a
        move y1,y0
        add y0,a                ; the modulated phase
        move a1,y1              ; wrapped again: modulation can push it over
        move y1,a
        abs a
        move #>$7fffff,b
        move a,x0
        move x0,y0
        move b,a
        sub y0,a
        move a,x0
        move y1,y0
        mpy y0,x0,a
        asl a
        asl a                   ; the carrier's sine
        move a,x1
; ---- envelope and output ------------------------------------------------
        move x:(r5+@ENV@),b
        move b,x0
        move x:(r5+@DE@),y0
        mpy y0,x0,a
        sub a,b
        move b,x:(r5+@ENV@)
; ⚠️ THE INDEX FALLS, AND NOW ON ITS OWN RATE. A fixed index is an FM TONE,
; not a drum: what makes a struck bell a bell is that it is bright for ten
; milliseconds and pure afterwards. It used to fall with the amplitude
; envelope, which made "how long" and "how bright for how long" one control.
        move x:(r5+@FIE@),a
        move a,x0
        move x:(r5+@FIR@),y0
        mpy y0,x0,a
        move x0,b
        sub a,b
        move b,x:(r5+@FIE@)
        move b,x0
        move x:(r5+@FIA@),y0
        mpy y0,x0,a
        move a,x0
        move x0,x:(r5+@FIX@)
; ⚠️ RELOAD THE AMPLITUDE ENVELOPE. b held it until the index block above
; started keeping its OWN envelope there; the output's level is still the
; amplitude envelope's and reading b here would scale the note by its
; brightness instead.
        move x:(r5+@ENV@),y0
        move x1,x0
        mpy y0,x0,a
        move a,x0
        move x:(r5+@GAIN@),y0
        mpy y0,x0,a
        asl a                   ; DRIVE (knob 5)
        asl a
        asl a
        move a,x:(r0)+
        move a,x:(r0)+
zf07:
zf05:
        rts
; --- zf06: the trig -------------------------------------------------------
; ⚠️ BOTH PHASES TO ZERO, AND THE INDEX BACK TO FULL. Two pitched oscillators
; starting at a stale phase give a click whose pitch is not the machine's, and
; an index left where the last note's envelope dropped it makes the second hit
; of a pattern duller than the first -- which reads as a broken velocity.
zf06:
        clr a
        move a,x:(r5+@FPC@)
        move a,x:(r5+@FPM@)
        move x:(r5+@FIA@),a
        move a,x:(r5+@FIX@)
        move #>$7fffff,a
        move a,x:(r5+@ENV@)
        move a,x:(r5+@FIE@)     ; the index envelope starts full too
        rts
