#!/usr/bin/env python3
"""Generate original coefficient tables and freestanding ColdFire assembly."""
import math
import pathlib
import subprocess
import sys
import tempfile
HERE=pathlib.Path(__file__).resolve().parent
ROOT=HERE.parents[1]
def table(name, values, typ='int32_t'):
    return 'static const '+typ+' '+name+'[] = {\n'+',\n'.join('    '+', '.join(str(v) for v in values[i:i+8]) for i in range(0,len(values),8))+'\n};\n'
def tables():
    # Service notes pp.11-12: R473/474 + R530/532, loaded by R531/533.
    # Normalize DC gain: level belongs to AMP, not this filter control.
    nominal=1/(2*math.pi*(3200*10000/(3200+10000))*10e-9)
    lpf=[0]+[500*(nominal/500)**((i-1)/63) if i<=64 else
              nominal*(18000/nominal)**((i-64)/63) for i in range(1,128)]
    return ('/* Generated LPF display frequencies; synthesis tables live in dsp808/dsp909. */\n'
            +table('ab_lpf_freq',[round(f) for f in lpf]))
FLAGS=['-mcpu=5407','-msoft-float','-O2','-ffreestanding','-fno-builtin','-fno-common','-fno-jump-tables','-fno-asynchronous-unwind-tables','-fno-ident','-fomit-frame-pointer','-fno-zero-initialized-in-bss','-Wall','-Wextra','-Werror']
def _asm_bytes(text, tmp, tag):
    """Assemble one .s source and return its flat output bytes, or None."""
    src=pathlib.Path(tmp)/(tag+'.s'); src.write_text(text)
    obj=pathlib.Path(tmp)/(tag+'.o'); flat=pathlib.Path(tmp)/(tag+'.bin')
    try:
        subprocess.run(['m68k-elf-as','-mcpu=5475',str(src),'-o',str(obj)],
                       check=True,capture_output=True)
        subprocess.run(['m68k-elf-objcopy','-O','binary',str(obj),str(flat)],
                       check=True,capture_output=True)
    except (OSError,subprocess.CalledProcessError):
        return None
    return flat.read_bytes()


def _same_object(path, body):
    """True when the checked-in .s and the regenerated one assemble alike.

    Returns False -- i.e. keeps the gate failing -- if the assembler is not
    available or either side refuses to assemble, so a missing toolchain can
    never be mistaken for agreement.
    """
    with tempfile.TemporaryDirectory() as tmp:
        have=_asm_bytes(path.read_text(),tmp,'have')
        want=_asm_bytes(body,tmp,'want')
    return have is not None and want is not None and have==want


def main():
    check='--check' in sys.argv
    outputs={HERE/'tables.inc':tables()}
    with tempfile.TemporaryDirectory() as tmp:
        for name in ('engine','control'):
            if not (HERE/(name+'.c')).exists(): continue
            dest=pathlib.Path(tmp)/(name+'.s')
            # Local include is deliberately checked/generated before compiling.
            if not check: (HERE/'tables.inc').write_text(outputs[HERE/'tables.inc'])
            subprocess.run(['m68k-elf-gcc',*FLAGS,'-S',str(HERE/(name+'.c')),'-o',str(dest)],check=True)
            outputs[HERE/(name+'.s')]='| Generated by generate.py; edit '+name+'.c.\n'+dest.read_text()
    for path,body in outputs.items():
        if check:
            if not path.exists(): raise SystemExit(f'stale: {path}')
            if path.read_text()!=body:
                # ⚠️ TWO GCC VERSIONS SPELL THE SAME BYTES DIFFERENTLY, and a
                # text compare reads that as a stale file. gcc 14.2.0 emits a
                # string constant as `.base64 "AEB/QEAA"` where the author's
                # older gcc emitted `.string ""` + `.string "@\177@@"` -- the
                # same six bytes, and engine.s assembles to the identical
                # 524-byte object either way (2 Oct 2026, Linux container).
                # So when the TEXT differs, ask the assembler: identical
                # output bytes mean the checked-in .s still corresponds to
                # its .c, which is the only thing this gate is about. The
                # file is NOT rewritten -- the author's bytes stay the
                # oracle, and `--check` never writes.
                if path.suffix!='.s' or not _same_object(path,body):
                    raise SystemExit(
                        f'stale: {path}\n'
                        '  ⚠️ BEFORE REGENERATING, CHECK YOUR COMPILER. This gate is a\n'
                        '  compiler-identity oracle: it asserts the checked-in .s is what\n'
                        '  the AUTHOR\'S gcc made of the .c, and FLAGS carries -fno-ident,\n'
                        '  so no version marker survives in the file to compare against.\n'
                        '  A different gcc optimises differently and fails here with the\n'
                        '  module perfectly sound -- m68k-elf-gcc 14.2.0 recompiles\n'
                        '  control.c into 1,679 diff lines of equivalent but differently\n'
                        '  scheduled code (2 Oct 2026, Linux container), while engine.c\n'
                        '  differs only in string spelling and is accepted above.\n'
                        '  Running this WITHOUT --check would replace the author\'s proven\n'
                        '  bytes with your compiler\'s unproven ones. Do that only when\n'
                        '  you mean to change the module, and re-measure its gates after.\n'
                        '  Otherwise report this gate BLOCKED on a toolchain mismatch.')
                print(f'  {path.name}: text differs, assembles identically '
                      f'(compiler-version spelling, not a stale file)')
        else: path.write_text(body)
    print('Analog Bassdrum generated sources match' if check else 'Analog Bassdrum sources generated')
if __name__=='__main__': main()
